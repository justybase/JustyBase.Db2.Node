export function isNullableSqlType(type: number): boolean { return (type & 1) === 1; }
export function baseSqlType(type: number): number { return isNullableSqlType(type) ? type - 1 : type; }
export function sqlTypeName(type: number): string {
  return SQL_TYPE_NAMES.get(type) ?? `SQLType(${type})`;
}
